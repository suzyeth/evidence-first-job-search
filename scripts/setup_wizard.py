# -*- coding: utf-8 -*-
"""首次设置向导:回答几个问题,自动生成 sweep_config.json 和 boardsweep_config.json,不用手写 JSON 或正则。

用法:
  python setup_wizard.py           # 一问一答;直接回车就用括号里的默认值
  python setup_wizard.py --lang en

已有配置时会先备份成 .bak,并保留你在跟踪的岗位(tracked)和已填的公司招聘板。
"""
from __future__ import annotations

import json
import os
import re
import shutil
import sys
from typing import Callable

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import keyword_suggest as ks  # noqa: E402
from friendly import load_json_friendly, parse_choices, words_to_regex  # noqa: E402
from i18n import apply_lang_arg, tr  # noqa: E402

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
SWEEP_CONFIG = os.path.join(SCRIPT_DIR, "sweep_config.json")
BOARD_CONFIG = os.path.join(SCRIPT_DIR, "boardsweep_config.json")
SWEEP_EXAMPLE = os.path.join(SCRIPT_DIR, "sweep_config.example.json")
BOARD_EXAMPLE = os.path.join(SCRIPT_DIR, "boardsweep_config.example.json")

DEFAULT_LOCATION = "London, UK"
DEFAULT_YEARS = 3
DEFAULT_TITLES_PER_FAMILY = 4
OWN_TRACK = "MY"
SENIOR_REGEX = ("senior|\\bsr\\b|staff|lead|principal|head of|director|manager,|vp |vice president|"
                "intern(ship)?|undergraduate|placement year")
JUNIOR_ONLY_REGEX = "intern(ship)?|undergraduate|placement year"

Ask = Callable[[str], str]
Say = Callable[[str], None]


# ---------------------------------------------------------------- questions

def ask_text(ask: Ask, prompt: str, default: str) -> str:
    answer = ask(f"{prompt} [{default}]: ").strip()
    return answer or default


def ask_int(ask: Ask, say: Say, prompt: str, default: int, lo: int = 0, hi: int = 30) -> int:
    while True:
        answer = ask(f"{prompt} [{default}]: ").strip()
        if not answer:
            return default
        if answer.isdigit() and lo <= int(answer) <= hi:
            return int(answer)
        say(tr(f"  请输入 {lo} 到 {hi} 之间的数字。", f"  Please type a number from {lo} to {hi}."))


def ask_yes(ask: Ask, prompt: str, default: bool = True) -> bool:
    hint = "Y/n" if default else "y/N"
    answer = ask(f"{prompt} [{hint}]: ").strip().lower()
    if not answer:
        return default
    return answer[0] in "y是好对1"


def split_titles(raw: str) -> list[str]:
    return [t.strip().lower() for t in re.split(r"[,，、;；\n]+", raw) if t.strip()]


# ---------------------------------------------------------------- building blocks

def location_regex(location: str) -> str:
    """'Berlin, Germany' -> 'berlin|germany|remote' for the employer-board filter."""
    parts = [p.strip().lower() for p in re.split(r"[,/]+", location) if p.strip()]
    if any(p in ("uk", "united kingdom", "england", "london") for p in parts):
        parts += ["united kingdom", "uk", "england"]
    words = words_to_regex(dict.fromkeys(parts))
    return f"{words}|remote" if words else "remote"


def families_from_suggestions(suggestions: list[ks.Suggestion]) -> list[dict]:
    """Group title-level suggestions back into families, keeping the suggestion order (best first)."""
    fams: dict[str, dict] = {}
    for s in suggestions:
        fam = fams.setdefault(s.family, {"name": s.family, "track": s.track, "tier": s.tier, "score": s.score,
                                         "matched": s.matched, "missing": s.missing, "evidence": s.evidence,
                                         "titles": []})
        fam["titles"].append(s)
    return list(fams.values())


def choose_titles(family: dict, per_family: int) -> list[ks.Suggestion]:
    """Entry-level titles first; when past scans are known, titles that actually returned jobs first."""
    titles = list(family["titles"])
    if any(t.seen_in_logs is not None for t in titles):
        titles.sort(key=lambda t: (-(t.seen_in_logs or 0), t.level != "entry"))
    return titles[:per_family]


def build_sweep_config(picks: list[tuple[str, str]], location: str, exclude_senior: bool,
                       previous: dict | None) -> dict:
    """picks = [(track, title)]. Keeps tracked jobs and agency / noise lists from the previous config."""
    base = load_json_friendly(SWEEP_EXAMPLE)
    prev = previous or {}
    by_track: dict[str, list[str]] = {}
    for track, title in picks:
        by_track.setdefault(track, []).append(title)
    config = {
        "_readme": tr("由 setup_wizard.py 生成。想改搜索词就重新运行向导,或运行 keyword_suggest.py --apply。"
                      "queries = [方向代码, 搜索词, 地点];tracked = 你在跟踪的岗位(用 sweep.py add 添加)。",
                      "Generated by setup_wizard.py. To change search words, run the wizard again or "
                      "keyword_suggest.py --apply. queries = [track, search words, location]; tracked = jobs you "
                      "follow (add them with sweep.py add)."),
        "queries": [[track, title, location] for track, title in picks],
        "tracked": prev.get("tracked", []),
        "exclude_title_regex": SENIOR_REGEX if exclude_senior else JUNIOR_ONLY_REGEX,
        "noise_company_regex": prev.get("noise_company_regex", base.get("noise_company_regex", "")),
        "agency_company_regex": prev.get("agency_company_regex", base.get("agency_company_regex", "")),
        "title_relevance": {track: words_to_regex(titles) for track, titles in by_track.items()},
        "display_track_priority": list(by_track),
        "indeed_country_default": base.get("indeed_country_default", "UK"),
        "indeed_country_by_location": base.get("indeed_country_by_location", {}),
    }
    return config


def build_board_config(titles: list[str], location: str, max_years: int, previous: dict | None) -> dict:
    base = load_json_friendly(BOARD_EXAMPLE)
    prev = previous or {}
    config = {key: prev.get(key, []) for key in ("ashby", "greenhouse", "lever", "workable", "teamtailor")}
    config["_readme"] = tr("由 setup_wizard.py 生成。在 ashby / greenhouse / lever / workable / teamtailor 里填目标公司"
                           "的招聘板 slug(招聘页网址里的公司代号,例如 jobs.ashbyhq.com/<slug>)。",
                           "Generated by setup_wizard.py. Add target companies' board slugs (the company code in "
                           "the careers URL, e.g. jobs.ashbyhq.com/<slug>) under ashby / greenhouse / lever / "
                           "workable / teamtailor.")
    config["want_title_regex"] = words_to_regex(titles) or base.get("want_title_regex", "")
    config["senior_title_regex"] = prev.get("senior_title_regex", base.get("senior_title_regex", ""))
    config["max_years"] = max_years
    config["location_regex"] = location_regex(location)
    return config


def _write(path: str, data: dict) -> str | None:
    backup = None
    if os.path.exists(path):
        backup = path + ".bak"
        shutil.copyfile(path, backup)
    with open(path, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
        f.write("\n")
    return backup


def _load_if_valid(path: str, say: Say) -> dict | None:
    if not os.path.exists(path):
        return None
    try:
        return load_json_friendly(path)
    except SystemExit as exc:
        say(str(exc))
        say(tr("  这份旧配置读不出来,会被新配置替换(旧文件先备份成 .bak)。",
               "  The old config can't be read; it will be replaced (a .bak copy is kept)."))
        return None


# ---------------------------------------------------------------- wizard

def pick_from_fact_base(ask: Ask, say: Say, master_path: str, previous: dict | None) -> list[tuple[str, str]]:
    with open(master_path, "r", encoding="utf-8-sig") as f:
        master = f.read()
    suggestions = ks.suggest(master, load_json_friendly(ks.TAXONOMY_PATH), previous)
    if os.path.isdir(ks.LOG_DIR):
        ks.count_in_logs(suggestions)
    families = families_from_suggestions(suggestions)
    if not families:
        say(tr("  事实库里的证据还不够推荐方向,改为手动输入岗位名。",
               "  Not enough evidence in the fact base yet; type job titles instead."))
        return []
    say(tr("\n根据你的事实库,这些方向有证据支撑(每个方向会搜几个常见岗位名):",
           "\nYour fact base supports these directions (each searches a few common titles):"))
    for i, fam in enumerate(families, 1):
        tier = ks.TIER_NAMES[fam["tier"]][0 if tr("zh", "en") == "zh" else 1]
        examples = ", ".join(t.title for t in fam["titles"][:3])
        say(f"  {i:>2}. [{tier}] {fam['name']} · {round(fam['score'] * 100)}%  — {examples}")
        if fam["missing"]:
            say(tr("      缺:", "      Missing: ") + ", ".join(fam["missing"]))
    core = [i for i, fam in enumerate(families, 1) if fam["tier"] == "core"]
    default = ",".join(map(str, core or [1]))
    raw = ask_text(ask, tr("选哪些方向?输入编号,例如 1,3,5-7", "Which directions? Type numbers, e.g. 1,3,5-7"), default)
    chosen = [families[i - 1] for i in parse_choices(raw, len(families))]
    per_family = ask_int(ask, say, tr("每个方向搜几个岗位名?(越多扫得越慢)", "How many titles per direction? (more = slower)"),
                         DEFAULT_TITLES_PER_FAMILY, 1, 12)
    picks: list[tuple[str, str]] = []
    for fam in chosen:
        for s in choose_titles(fam, per_family):
            picks.append((s.track, s.title))
    return picks


def run(ask: Ask = input, say: Say = print, master_path: str | None = None) -> int:
    say(tr("=== 首次设置 ===\n回答几个问题,我来生成搜索配置。直接回车 = 用方括号里的默认值。\n",
           "=== Setup ===\nAnswer a few questions and the search config is written for you. "
           "Press Enter to accept the default in brackets.\n"))
    previous = _load_if_valid(SWEEP_CONFIG, say)
    previous_board = _load_if_valid(BOARD_CONFIG, say)
    if previous is not None:
        say(tr(f"已有配置:{SWEEP_CONFIG}(含 {len(previous.get('queries', []))} 个搜索词、"
               f"{len(previous.get('tracked', []))} 个在跟踪的岗位)。",
               f"Existing config: {SWEEP_CONFIG} ({len(previous.get('queries', []))} search words, "
               f"{len(previous.get('tracked', []))} tracked jobs)."))
        if not ask_yes(ask, tr("重新生成搜索词吗?(在跟踪的岗位会保留,旧文件备份成 .bak)",
                               "Regenerate the search words? (tracked jobs are kept; the old file is backed up)")):
            say(tr("没有改动。", "Nothing changed."))
            return 0

    location = ask_text(ask, tr("在哪里找工作?(城市, 国家)", "Where are you looking? (city, country)"), DEFAULT_LOCATION)
    max_years = ask_int(ask, say, tr("JD 要求超过几年经验就提醒你?", "Flag jobs asking for more than how many years?"),
                        DEFAULT_YEARS)
    exclude_senior = ask_yes(ask, tr("过滤掉 Senior / Lead / 总监 这类高级岗位?", "Filter out Senior / Lead / Director roles?"))

    master_path = master_path or ks.find_master()
    picks: list[tuple[str, str]] = []
    if master_path:
        say(tr(f"\n找到你的事实库:{master_path}", f"\nFound your fact base: {master_path}"))
        picks = pick_from_fact_base(ask, say, master_path, previous)
    else:
        say(tr("\n没找到事实库 master-cv-data.md。可以先手动输入岗位名;以后填好事实库,再运行一次向导就能拿到推荐。",
               "\nNo fact base (master-cv-data.md) found. Type job titles for now; fill in the fact base later and "
               "run the wizard again for suggestions."))
    extra = ask_text(ask, tr("还想加别的岗位名吗?用逗号隔开(英文岗位名,例如 data analyst, ux researcher)",
                             "Any other job titles? Separate with commas (e.g. data analyst, ux researcher)"), "")
    seen = {t for _, t in picks}
    for title in split_titles(extra):
        if title not in seen:
            picks.append((OWN_TRACK, title))
            seen.add(title)
    if not picks:
        say(tr("没有选任何岗位名,配置没有改动。", "No job titles chosen; nothing changed."))
        return 1

    sweep_cfg = build_sweep_config(picks, location, exclude_senior, previous)
    board_cfg = build_board_config([t for _, t in picks], location, max_years, previous_board)
    backups = [b for b in (_write(SWEEP_CONFIG, sweep_cfg), _write(BOARD_CONFIG, board_cfg)) if b]

    say(tr(f"\n✅ 设置完成:{len(picks)} 个搜索词 × LinkedIn 和 Indeed,地点 {location}。",
           f"\n✅ Done: {len(picks)} search words × LinkedIn and Indeed, location {location}."))
    for _, title in picks:
        say(f"   · {title}")
    if backups:
        say(tr("   旧配置备份:", "   Old config backed up: ") + ", ".join(backups))
    say(tr("\n下一步:回到菜单选「扫新岗位」;想直扫公司招聘页,在 boardsweep_config.json 里填公司代号。",
           "\nNext: choose \"Scan for new jobs\" in the menu. To scan company career pages directly, add company "
           "codes to boardsweep_config.json."))
    return 0


def main(argv: list[str] | None = None) -> int:
    argv = apply_lang_arg(list(sys.argv[1:] if argv is None else argv))
    master = argv[argv.index("--master") + 1] if "--master" in argv else None
    try:
        return run(master_path=master)
    except (KeyboardInterrupt, EOFError):
        print(tr("\n已取消,配置没有改动。", "\nCancelled; nothing changed."))
        return 1


if __name__ == "__main__":
    try:
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    except Exception:
        pass
    sys.exit(main())
